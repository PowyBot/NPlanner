def quest_uuid(key):
    return uuid.uuid5(NAMESPACE, "gtnhplanner:quest:" + key)


def line_uuid():
    return uuid.uuid5(NAMESPACE, "gtnhplanner:questline")


def high_low(u):
    # BetterQuesting stores a UUID as two signed 64-bit halves.
    return struct.unpack(">qq", u.bytes)


def encode(u):
    return base64.urlsafe_b64encode(u.bytes).decode()


def key_part(u):
    # BetterQuesting's translation keys use the URL-safe base64 UUID without its padding.
    return encode(u).replace("=", "")


def file_stem(name, u):
    return re.sub(r"[^A-Za-z0-9]", "", name)[:16] + "-" + encode(u)


def item(id_, damage, count):
    return {"Count:3": count, "Damage:2": damage, "OreDict:8": "", "id:8": id_}


def quest_json(q):
    u = quest_uuid(q["key"])
    high, low = high_low(u)
    icon_id, icon_damage = q["icon"]
    properties = {
        "autoClaim:1": 0,
        "desc:8": q["desc"],
        "globalShare:1": 1,
        "icon:10": item(icon_id, icon_damage, 1),
        "isGlobal:1": 0,
        "isMain:1": 0,
        "isSilent:1": 0,
        "lockedProgress:1": 0,
        "name:8": q["name"],
        "partySingleReward:1": 0,
        "questLogic:8": "AND",
        "repeatTime:3": -1,
        "repeat_relative:1": 1,
        "simultaneous:1": 0,
        "snd_complete:8": "random.levelup",
        "snd_update:8": "random.levelup",
        "taskLogic:8": "AND",
        "visibility:8": "NORMAL",
    }
    return u, {
        "properties:10": {"betterquesting:10": properties},
        "questIDHigh:4": high,
        "questIDLow:4": low,
        "rewards:9": {
            "0:10": {
                "ignoreDisabled:1": 0,
                "index:3": 0,
                "rewardID:8": "bq_standard:item",
                "rewards:9": {"0:10": item(LOOTBAG, BAG[q["tier"]], 1)},
            }
        },
        "tasks:9": {"0:10": {"index:3": 0, "plannerTask:8": q["task"], "taskID:8": "gtnhplanner:event"}},
    }


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, sort_keys=True, ensure_ascii=True)
        f.write("\n")


def main():
    shutil.rmtree(os.path.join(ROOT, "DefaultQuests"), ignore_errors=True)
    lu = line_uuid()
    lhigh, llow = high_low(lu)
    line_dir_name = file_stem(LINE["name"], lu)
    line_dir = os.path.join(ROOT, "DefaultQuests", "QuestLines", line_dir_name)
    quest_dir = os.path.join(ROOT, "DefaultQuests", "Quests", line_dir_name)
    write_json(os.path.join(line_dir, "QuestLine.json"), {
        "properties:10": {
            "betterquesting:10": {
                "bg_image:8": "",
                "bg_size:3": 256,
                "desc:8": LINE["desc"],
                "icon:10": item(LINE["icon"][0], LINE["icon"][1], 1),
                "name:8": LINE["name"],
                "visibility:8": "UNLOCKED",
            }
        },
        "questLineIDHigh:4": lhigh,
        "questLineIDLow:4": llow,
    })
    paths = [f"DefaultQuests/QuestLines/{line_dir_name}/QuestLine.json"]

    lang = [LANG_BEGIN, f"betterquesting.questline.{key_part(lu)}.name={LINE['name']}",
            f"betterquesting.questline.{key_part(lu)}.desc={LINE['desc']}", "gtnhplanner.task.name=Planner"]
    lang_it = [LANG_BEGIN, f"betterquesting.questline.{key_part(lu)}.name={LINE_IT[0]}",
               f"betterquesting.questline.{key_part(lu)}.desc={LINE_IT[1]}", "gtnhplanner.task.name=Pianificatore"]
    for task, (en, it) in TASK_TEXT.items():
        lang.append(f"gtnhplanner.task.{task.lower()}={en}")
        lang_it.append(f"gtnhplanner.task.{task.lower()}={it}")
    written = 0
    for q in QUESTS:
        if q.get("waits"):
            print(f"{q['key']}: waits for {q['waits']}, left out")
            continue
        u, data = quest_json(q)
        high, low = high_low(u)
        stem = file_stem(q["name"], u)
        x, y = q["pos"]
        write_json(os.path.join(line_dir, stem + ".json"),
                   {"questIDHigh:4": high, "questIDLow:4": low, "sizeX:3": 24, "sizeY:3": 24, "x:3": x, "y:3": y})
        paths.append(f"DefaultQuests/QuestLines/{line_dir_name}/{stem}.json")
        write_json(os.path.join(quest_dir, stem + ".json"), data)
        paths.append(f"DefaultQuests/Quests/{line_dir_name}/{stem}.json")
        lang.append(f"betterquesting.quest.{key_part(u)}.name={q['name']}")
        lang.append(f"betterquesting.quest.{key_part(u)}.desc={q['desc']}")
        lang_it.append(f"betterquesting.quest.{key_part(u)}.name={q['it'][0]}")
        lang_it.append(f"betterquesting.quest.{key_part(u)}.desc={q['it'][1]}")
        written += 1
    lang.append(LANG_END)
    lang_it.append(LANG_END)

    # Pack makers append this line to their own QuestLinesOrder.txt.
    with open(os.path.join(ROOT, "DefaultQuests", "QuestLinesOrder.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"{encode(lu)}: {LINE['name']}\n")
    with open(os.path.join(ROOT, "index.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(paths) + "\n")
    write_lang("en_US.lang", lang)
    write_lang("it_IT.lang", lang_it)
    print(f"Wrote {written} of {len(QUESTS)} quests in line {encode(lu)}")


def write_lang(name, lines):
    path = os.path.join(LANG_DIR, name)
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    block = "\n".join(lines)
    if LANG_BEGIN in text:
        text = re.sub(re.escape(LANG_BEGIN) + r".*?" + re.escape(LANG_END), lambda m: block, text, flags=re.S)
    else:
        text = (text.rstrip("\n") + "\n\n" if text else "") + block + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
